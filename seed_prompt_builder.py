def seed_if_empty(conn):
    if conn.execute("SELECT COUNT(*) AS n FROM prompt_categories").fetchone()["n"]:
        return
    for order, (key, label, items) in enumerate(SEED_DATA):
        cur = conn.execute(
            "INSERT INTO prompt_categories (key, label, sort_order) VALUES (?,?,?)",
            (key, label, order),
        )
        conn.executemany(
            "INSERT INTO prompt_items (category_id, text, sort_order) VALUES (?,?,?)",
            [(cur.lastrowid, text, i) for i, text in enumerate(items)],
        )
    conn.commit()
